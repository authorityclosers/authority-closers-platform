#!/usr/bin/env python3
"""Prove who can call every HTTP route, as a checked-in role × route table.

The generator composes the real application, enumerates every registered
method + path, and sends one request per actor and context against fictional
fixtures.  A row is ``allowed`` or ``denied`` only when the response proves it;
anything else is ``unproven`` and fails the gate until its fixture is fixed.
CI regenerates the table and fails on any difference from the committed file.
"""

from __future__ import annotations

