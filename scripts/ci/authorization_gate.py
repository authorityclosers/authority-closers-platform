def _settings(configuration: str, database_url: str, scratch: Path) -> Any:
    from pydantic import SecretStr

    from ac_platform.application.settings import Settings
    from scripts.ci.authorization_fixtures import ACADEMY_TENANT, OPERATIONS_TENANT

    values: dict[str, Any] = {
        "_env_file": None,
        "environment": "test",
        "database_url": database_url,
        "public_app_url": "https://learner.example.test",
        "admin_app_url": "https://admin.example.test",
        "coach_app_url": "https://coach.example.test",
        "api_url": "https://api.example.test",
        "public_learner_tenant_id": ACADEMY_TENANT,
        "operations_tenant_id": OPERATIONS_TENANT,
        "practice_arcade_preview_enabled": True,
        "learner_consent_version": "2026-01",
        "session_token_pepper": SecretStr(stable_token("session-pepper")),
        "release_id": "authorization-gate",
    }
    if configuration == "sales_xray":
        values.update(
            sales_xray_app_url="https://salesxray.example.test",
            sales_xray_acquisition_enabled=True,
            sales_xray_challenge_site_key="site-key-authorization-gate",
            sales_xray_acquisition_policy_revision="authorization-gate-v1",
            billing_enabled=True,
            billing_fake_provider_signing_key=SecretStr(stable_token("billing-fake-signing")),
        )
    return Settings(**values)


@asynccontextmanager
async def composed_app(configuration: str, database_url: str, scratch: Path):
    """Yield (app, settings, session factory) bound to one savepoint-isolated connection."""

    from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

    import ac_platform.db.session as db_session
    import ac_platform.http.app as app_module

    settings = _settings(configuration, database_url, scratch)
    engine = create_async_engine(database_url, pool_size=2, max_overflow=0)
    connection = await engine.connect()
    outer = await connection.begin()
    sessions = async_sessionmaker(
        bind=connection, join_transaction_mode="create_savepoint", expire_on_commit=False
    )
    originals = (
        app_module.settings,
        app_module.session_factory,
        app_module.engine,
        db_session.session_factory,
        app_module.compose_hosted_intake,
        app_module.compose_acquisition,
    )
    app_module.settings = settings
    app_module.session_factory = sessions
    app_module.engine = engine
    db_session.session_factory = sessions
    if configuration == "sales_xray":
        from scripts.ci.authorization_fixtures import sales_xray_runtime

        runtime = sales_xray_runtime(scratch / configuration, settings)
        app_module.compose_hosted_intake = lambda _settings: runtime.intake
        app_module.compose_acquisition = lambda _settings, _intake: runtime
    try:
        app = app_module.create_app()
        yield app, settings, sessions, connection
    finally:
        (
            app_module.settings,
            app_module.session_factory,
            app_module.engine,
            db_session.session_factory,
            app_module.compose_hosted_intake,
            app_module.compose_acquisition,
        ) = originals
        await outer.rollback()
        await connection.close()
        await engine.dispose()


def enumerate_routes(app: Any) -> list[tuple[str, str, Any]]:
    from fastapi.routing import iter_route_contexts

    routes: list[tuple[str, str, Any]] = []
    for route in iter_route_contexts(app.router.routes):
        for method in sorted(route.methods or ()):
            routes.append((method, route.path, route))
    return sorted(routes, key=lambda item: (item[1], item[0]))


