import asyncio
import base64
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from contextlib import asynccontextmanager, contextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from uuid import UUID, uuid4, uuid5

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "packages" / "python"))
os.environ.setdefault("AC_ENVIRONMENT", "test")
os.environ.setdefault("AC_EXTERNAL_SIDE_EFFECTS_HOLD", "true")
os.environ.setdefault("AC_EMAIL_PROVIDER", "fake")
os.environ.setdefault("AC_NATIVE_API_ENABLED", "1")

SCHEMA = "ac.authorization-expectations/1"
EXPECTATIONS = ROOT / "docs" / "security" / "authorization_expectations.json"
ACTORS = ("guest", "learner", "member", "admin", "owner", "staff", "service")
NAMESPACE = UUID("3b1c2d4e-5f60-4a7b-8c9d-0e1f2a3b4c5d")
# Problem codes that describe the request shape, not the caller's authority.
UNPROVEN_FORBIDDEN_CODES = frozenset(
    {
        "admin_surface_required",
        "coach_surface_route_denied",
        "request_origin_denied",
        "rate_limited",
        "sales_xray_surface_required",
        "surface_denied",
    }
)


class GateError(RuntimeError):
    """A bounded failure suitable for the one-line CI result."""


def stable_uuid(name: str) -> UUID:
    return uuid5(NAMESPACE, name)


def stable_token(name: str) -> str:
    """A deterministic 43-character opaque token for a fictional session."""

    digest = hashlib.sha256(f"authorization-gate:{name}".encode()).digest()
    return base64.urlsafe_b64encode(digest).decode().rstrip("=")


@dataclass(frozen=True, slots=True)
class Row:
    method: str
    path: str
    actor: str
    context: str
    outcome: str
    status: int | None
    configuration: str
    note: str = ""
    finding: str = ""

    @property
    def key(self) -> tuple[str, str, str, str]:
        return (self.path, self.method, self.actor, self.context)

    def as_json(self) -> dict[str, Any]:
        row: dict[str, Any] = {
            "method": self.method,
            "path": self.path,
            "actor": self.actor,
            "context": self.context,
            "outcome": self.outcome,
            "status": self.status,
            "configuration": self.configuration,
        }
        if self.note:
            row["note"] = self.note
        if self.finding:
            row["finding"] = self.finding
        return row


@dataclass(slots=True)
class Table:
    rows: list[Row] = field(default_factory=list)

    def sorted(self) -> list[Row]:
        order = {actor: index for index, actor in enumerate(ACTORS)}
        return sorted(
            self.rows, key=lambda row: (row.path, row.method, order[row.actor], row.context)
        )

    def routes(self) -> set[tuple[str, str]]:
        return {(row.method, row.path) for row in self.rows}

    def render(self) -> str:
        lines = [
            "{",
            f'  "schema": {json.dumps(SCHEMA)},',
            '  "note": "Generated by scripts/ci/authorization_gate.py. Edit only on purpose: '
            "a changed row means who can do what changed. finding rows record outcomes that "
            'look wrong but are left as they are until the CEO/CTO decide.",',
            '  "rows": [',
        ]
        rows = self.sorted()
        for index, row in enumerate(rows):
            suffix = "," if index + 1 < len(rows) else ""
            lines.append("    " + json.dumps(row.as_json(), ensure_ascii=False) + suffix)
        lines.extend(["  ]", "}", ""])
        return "\n".join(lines)

    @classmethod
    def load(cls, path: Path) -> Table:
        document = json.loads(path.read_text(encoding="utf-8"))
        if document.get("schema") != SCHEMA:
            raise GateError(f"{path} does not carry schema {SCHEMA}")
        rows = [
            Row(
                method=item["method"],
                path=item["path"],
                actor=item["actor"],
                context=item["context"],
                outcome=item["outcome"],
                status=item.get("status"),
                configuration=item["configuration"],
                note=item.get("note", ""),
                finding=item.get("finding", ""),
            )
            for item in document["rows"]
        ]
        return cls(rows)


def classify(status: int, body: Any, *, route_allowed: bool = False) -> tuple[str, str]:
    """Map one response to ``allowed``, ``denied`` or ``unproven`` with a note.

    A 404 proves a denial only once another non-foreign context on the same
    route was allowed: the route and its fixture are then known to work, so
    "not found" is the deliberate non-disclosure of a resource the caller may
    not see.  Without that proof a 404 stays unproven (a missing fixture).
    """

    code = body.get("code") if isinstance(body, dict) else None
    if 200 <= status < 400:
        return "allowed", ""
    if status == 401:
        return "denied", "authentication required"
    if status == 403:
        if code in UNPROVEN_FORBIDDEN_CODES:
            return "unproven", f"request shape rejected: {code}"
        return "denied", str(code or "forbidden")
    if status == 404 and route_allowed:
        return "denied", "hidden: 404 on a route another context reached"
    if status == 404:
        return "unproven", f"404 {code or ''}".strip()
    if status == 422:
        return "unproven", f"422 invalid request: {_detail(body)}"
    if status == 429:
        return "unproven", "429 rate limited"
    if status >= 500:
        return "unproven", f"{status} {code or 'server error'}"
    return "unproven", f"{status} {code or ''}".strip()


def _detail(body: Any) -> str:
    if isinstance(body, dict):
        detail = body.get("detail")
        if isinstance(detail, list):
            return "; ".join(
                f"{'.'.join(str(part) for part in item.get('loc', []))}: {item.get('msg', '')}"
                for item in detail[:3]
            )
        if isinstance(detail, str):
            return detail
        if "title" in body:
            return str(body.get("title"))
    return ""


def compare(expected: Table, actual: Table) -> list[str]:
    """Human-readable differences; empty when the committed table is exact."""

    problems: list[str] = []
    expected_rows = {row.key: row for row in expected.rows}
    actual_rows = {row.key: row for row in actual.rows}
    for route in sorted(actual.routes() - expected.routes()):
        problems.append(f"route without a row: {route[0]} {route[1]}")
    for route in sorted(expected.routes() - actual.routes()):
        problems.append(f"row for a route that no longer exists: {route[0]} {route[1]}")
    for key in sorted(set(expected_rows) & set(actual_rows)):
        before, after = expected_rows[key], actual_rows[key]
        if (before.outcome, before.status, before.configuration, before.note) != (
            after.outcome,
            after.status,
            after.configuration,
            after.note,
        ):
            problems.append(
                f"drift: {key[1]} {key[0]} as {key[2]}/{key[3]}: "
                f"{before.outcome} ({before.status}) -> {after.outcome} ({after.status}) {after.note}"
            )
    for key in sorted(set(actual_rows) - set(expected_rows)):
        if (key[1], key[0]) in expected.routes():
            problems.append(f"row missing for {key[1]} {key[0]} as {key[2]}/{key[3]}")
    for key in sorted(set(expected_rows) - set(actual_rows)):
        if (key[1], key[0]) in actual.routes():
            problems.append(f"stale row for {key[1]} {key[0]} as {key[2]}/{key[3]}")
    for row in actual.sorted():
        if row.outcome == "unproven":
            problems.append(
                f"unproven: {row.method} {row.path} as {row.actor}/{row.context}: {row.note}"
            )
    return problems


def carry_findings(previous: Table | None, table: Table) -> Table:
    """Keep hand-written ``finding`` notes for rows whose key still exists."""

    if previous is None:
        return table
    findings = {row.key: row.finding for row in previous.rows if row.finding}
    return Table(
        [
            Row(**{**row.__dict__, "finding": findings.get(row.key, "")})
            if row.key in findings
            else row
            for row in table.rows
        ]
    )


# --- disposable PostgreSQL ------------------------------------------------------------


def _database_url() -> str:
    raw = os.environ.get("AC_AUTHORIZATION_GATE_DATABASE_URL") or os.environ.get(
        "AC_TEST_DATABASE_URL"
    )
    if not raw:
        raise GateError("AC_TEST_DATABASE_URL (loopback PostgreSQL) is required")
    from sqlalchemy.engine import make_url

    url = make_url(raw)
    if url.get_backend_name() != "postgresql" or url.host not in {"127.0.0.1", "localhost", "::1"}:
        raise GateError("the authorization gate only runs against loopback PostgreSQL")
    return url.set(drivername="postgresql+psycopg").render_as_string(hide_password=False)


@contextmanager
def disposable_schema() -> Iterator[str]:
    """Create, migrate and finally drop one schema; yield its scoped URL."""

    from sqlalchemy import create_engine
    from sqlalchemy.engine import make_url
    from sqlalchemy.schema import CreateSchema, DropSchema

    base = make_url(_database_url())
    schema = f"authorization_gate_{uuid4().hex}"
    admin = create_engine(base, pool_pre_ping=True)
    created = False
    try:
        with admin.begin() as connection:
            connection.execute(CreateSchema(schema))
        created = True
        environment = os.environ.copy()
        environment.update(
            AC_DATABASE_URL=base.render_as_string(hide_password=False),
            AC_DATABASE_MIGRATOR_URL=base.render_as_string(hide_password=False),
            AC_ENVIRONMENT="test",
            PGOPTIONS=f"-csearch_path={schema}",
            PYTHONPATH=str(ROOT / "packages" / "python"),
        )
        result = subprocess.run(  # noqa: S603 - fixed Alembic command on a disposable schema
            [sys.executable, "-m", "alembic", "-c", "alembic.ini", "upgrade", "head"],
            cwd=ROOT,
            env=environment,
            capture_output=True,
            text=True,
            timeout=600,
            check=False,
        )
        if result.returncode:
            raise GateError(f"migration failed (exit {result.returncode})")
        yield base.set(query={**base.query, "options": f"-csearch_path={schema}"}).render_as_string(
            hide_password=False
        )
    finally:
        if created:
            with admin.begin() as connection:
                connection.execute(DropSchema(schema, cascade=True))
        admin.dispose()


