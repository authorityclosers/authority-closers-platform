class _FreshLimiter:
    """Give every gate request an untouched rate-limit bucket.

    The limiter is the real middleware; only its in-memory state is reset so
    the gate's own request volume never turns an authorization outcome into 429.
    """

    instances: list[Any] = []

    @classmethod
    def install(cls, app_module: Any) -> Any:
        from ac_platform.http.rate_limits import RateLimitMiddleware

        class Recording(RateLimitMiddleware):
            def __init__(self, *args: Any, **kwargs: Any) -> None:
                super().__init__(*args, **kwargs)
                cls.instances.append(self)

        original = app_module.RateLimitMiddleware
        app_module.RateLimitMiddleware = Recording
        return original

    @classmethod
    def reset(cls) -> None:
        from ac_platform.http.rate_limits import InMemoryTokenBucketLimiter

        for instance in cls.instances:
            instance.limiter = InMemoryTokenBucketLimiter()


async def _send(client: Any, connection: Any, method: str, plan: Any) -> tuple[int, Any]:
    """Run one planned request inside its own savepoint; nothing persists."""

    savepoint = await connection.begin_nested()
    try:
        _FreshLimiter.reset()
        if plan.etag_from:
            probe = await client.get(
                plan.etag_from,
                headers=plan.headers,
                cookies=plan.cookies,
                extensions={"client": plan.client},
            )
            etag = probe.headers.get("etag")
            if etag is None and probe.headers.get("content-type", "").startswith(
                "application/json"
            ):
                value: Any = probe.json()
                for part in (plan.etag_json or "etag").split("."):
                    value = (
                        value[int(part)]
                        if isinstance(value, list) and part.isdigit() and int(part) < len(value)
                        else value.get(part)
                        if isinstance(value, dict)
                        else None
                    )
                etag = value if isinstance(value, str) else None
            if etag:
                plan.headers["if-match"] = etag
        response = await client.request(
            method,
            plan.url,
            headers=plan.headers,
            cookies=plan.cookies,
            content=plan.content,
            extensions={"client": plan.client},
        )
        status = response.status_code
        try:
            body = response.json()
        except ValueError:
            body = None
    except Exception as error:  # noqa: BLE001 - recorded as unproven, never hidden
        status, body = 599, {"code": type(error).__name__}
    finally:
        await savepoint.rollback()
    return status, body


async def _execute(
    configuration: str,
    database_url: str,
    scratch: Path,
    *,
    seen: set[tuple[str, str]],
    prefixes: tuple[str, ...],
) -> list[Row]:
    import httpx

    import ac_platform.http.app as app_module
    from scripts.ci.authorization_fixtures import World, request_plan, seed_world

    rows: list[Row] = []
    original_limiter = _FreshLimiter.install(app_module)
    try:
        async with composed_app(configuration, database_url, scratch) as (
            app,
            settings,
            sessions,
            connection,
        ):
            world: World = await seed_world(sessions, settings)
            transport = httpx.ASGITransport(app=app, raise_app_exceptions=False)
            async with httpx.AsyncClient(
                transport=transport, base_url="https://learner.example.test"
            ) as client:
                for method, path, route in enumerate_routes(app):
                    if (method, path) in seen or (prefixes and not path.startswith(prefixes)):
                        continue
                    seen.add((method, path))
                    responses: list[tuple[Any, int, Any]] = []
                    for plan in request_plan(world, settings, method, path, route):
                        if plan.skip:
                            responses.append((plan, 0, None))
                            continue
                        status, body = await _send(client, connection, method, plan)
                        responses.append((plan, status, body))
                    route_allowed = any(
                        not plan.foreign and 200 <= status < 400 for plan, status, _ in responses
                    )
                    for plan, status, body in responses:
                        if plan.skip:
                            rows.append(
                                Row(
                                    method,
                                    path,
                                    plan.actor,
                                    plan.context,
                                    "unproven",
                                    None,
                                    configuration,
                                    plan.skip,
                                )
                            )
                            continue
                        outcome, note = classify(status, body, route_allowed=route_allowed)
                        rows.append(
                            Row(
                                method,
                                path,
                                plan.actor,
                                plan.context,
                                outcome,
                                status,
                                configuration,
                                note,
                            )
                        )
    finally:
        app_module.RateLimitMiddleware = original_limiter
        _FreshLimiter.instances.clear()
    return rows


def generate(*, prefixes: tuple[str, ...] = ()) -> Table:
    rows: list[Row] = []
    seen: set[tuple[str, str]] = set()
    with disposable_schema() as database_url, tempfile.TemporaryDirectory() as scratch:
        for configuration in ("sales_xray", "academy"):
            rows.extend(
                asyncio.run(
                    _execute(
                        configuration, database_url, Path(scratch), seen=seen, prefixes=prefixes
                    )
                )
            )
    return Table(rows)


def summary(table: Table, problems: list[str]) -> str:
    routes = len(table.routes())
    drift = sum(1 for item in problems if item.startswith("drift:"))
    unproven = sum(1 for item in problems if item.startswith("unproven:"))
    if not problems:
        return f"authorization-gate: PASS ({routes} routes, 0 drift)"
    return f"authorization-gate: FAIL ({routes} routes, {drift} drift, {unproven} unproven, {len(problems)} problems)"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "check"))
    parser.add_argument("--output", type=Path, default=EXPECTATIONS)
    parser.add_argument(
        "--prefix", action="append", default=[], help="limit to route path prefixes"
    )
    args = parser.parse_args(argv)
    previous = Table.load(args.output) if args.output.exists() else None
    try:
        table = carry_findings(previous, generate(prefixes=tuple(args.prefix)))
    except GateError as error:
        print(f"authorization-gate: FAIL ({error})")
        return 2
    if args.command == "generate":
        args.output.write_text(table.render(), encoding="utf-8")
        problems = [item for item in compare(table, table)]
        print(summary(table, problems))
        for item in problems:
            print(item)
        return 0
    if previous is None:
        print(f"authorization-gate: FAIL ({args.output} is missing)")
        return 1
    problems = compare(previous, table)
    if previous.render() != table.render() and not problems:
        problems.append("rendered table differs from the committed file")
    print(summary(table, problems))
    for item in problems:
        print(item)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
