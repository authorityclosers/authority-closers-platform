const metric = (
  key: string,
  kind: string,
  label: string,
  unit: string,
  base: number | null,
  head: number | null,
  verdict: string,
  samples: [number, number],
  regression = false,
) => ({
  key,
  kind,
  label,
  unit,
  base,
  head,
  base_samples: samples[0],
  head_samples: samples[1],
  change:
    base === null || head === null
      ? null
      : unit === "share"
        ? Math.round((head - base) * 10_000) / 10_000
        : base
          ? Math.round((head / base - 1) * 10_000) / 10_000
          : null,
  verdict,
  regression,
});

