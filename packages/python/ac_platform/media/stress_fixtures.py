def _verify_typed_gate(
    verifier: object,
    protocol: type[object],
    method_name: str,
    **kwargs: object,
) -> None:
    if not isinstance(verifier, protocol):
        raise _deny("a typed media authorization verifier is required")
    method = getattr(verifier, method_name, None)
    if not callable(method):
        raise _deny("a typed media authorization verifier is required")
    try:
        verified = method(**kwargs)
    except Exception as error:  # noqa: BLE001 - fail closed at the app boundary
        raise _deny("media authorization verifier failed") from error
    if verified is not True:
        raise _deny("media authorization verifier did not attest the fixture")


def _verify_playback_scope(
    authorization_context: object, playback_grant: object
) -> tuple[MediaAuthorizationContext, PlaybackGrantDescriptor]:
    """Require the server-created opaque scope before calling an external verifier."""

    if not isinstance(authorization_context, MediaAuthorizationContext):
        raise _deny("a server-created media authorization context is required")
    if not isinstance(playback_grant, PlaybackGrantDescriptor):
        raise _deny("a server-created playback grant is required")
    if playback_grant.authorization != authorization_context:
        raise _deny("playback grant authorization context does not match")
    return authorization_context, playback_grant


def compose_staging_test_fixture_source(
    *,
    environment: str,
    enabled: bool,
    fixture_id: str,
    cache_root: Path,
    provider_activation_verifier: FixtureProviderActivationVerifier,
    playback_grant_verifier: FixturePlaybackGrantVerifier,
    authorization_context: MediaAuthorizationContext,
    playback_grant: PlaybackGrantDescriptor,
) -> _StagingTestFixtureSource:
    """Return a verified local fixture only after all staging/test gates pass."""

    if environment == "production":
        raise _deny("production cannot compose media stress fixtures")
    if environment not in _ALLOWED_ENVIRONMENTS:
        raise _deny("media stress fixtures require test, development, or staging environment")
    if enabled is not True:
        raise _deny("media stress fixtures require explicit opt-in")
    root = _canonical_cache_root(cache_root)
    fixture, manifest_sha256 = _load_registry_fixture(fixture_id)
    source = _verify_registry_fixture(fixture, manifest_sha256, cache_root=root)
    authorization_context, playback_grant = _verify_playback_scope(
        authorization_context, playback_grant
    )
    _verify_typed_gate(
        provider_activation_verifier,
        FixtureProviderActivationVerifier,
        "verify_fixture_provider_activation",
        authorization_context=authorization_context,
        playback_grant=playback_grant,
        environment=environment,
        fixture_id=source.fixture_id,
        manifest_sha256=source.manifest_sha256,
    )
    _verify_typed_gate(
        playback_grant_verifier,
        FixturePlaybackGrantVerifier,
        "verify_fixture_playback_grant",
        authorization_context=authorization_context,
        playback_grant=playback_grant,
        fixture_id=source.fixture_id,
        source_sha256=source.source_sha256,
        manifest_sha256=source.manifest_sha256,
        content_type=source.content_type,
        width=source.width,
        height=source.height,
        duration_seconds=source.duration_seconds,
    )
    return source


def compose_staging_test_fixture_source_from_settings(
    settings: Any,
    *,
    fixture_id: str,
    provider_activation_verifier: FixtureProviderActivationVerifier,
    playback_grant_verifier: FixturePlaybackGrantVerifier,
    authorization_context: MediaAuthorizationContext,
    playback_grant: PlaybackGrantDescriptor,
) -> _StagingTestFixtureSource:
    """Use the validated settings cache root; callers cannot override it."""

    environment = getattr(settings, "environment", None)
    enabled = getattr(settings, "media_stress_fixtures_enabled", False)
    configured_root = getattr(settings, "media_stress_fixtures_cache_root", None)
    if not isinstance(environment, str):
        raise _deny("fixture settings have no valid environment")
    if not isinstance(configured_root, str) or not configured_root.strip():
        raise _deny("fixture settings have no configured cache root")
    return compose_staging_test_fixture_source(
        environment=environment,
        enabled=enabled,
        fixture_id=fixture_id,
        cache_root=Path(configured_root.strip()),
        provider_activation_verifier=provider_activation_verifier,
        playback_grant_verifier=playback_grant_verifier,
        authorization_context=authorization_context,
        playback_grant=playback_grant,
    )


