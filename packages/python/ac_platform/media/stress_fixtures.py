"""Fail-closed composition for non-production media stress fixtures.

The acquisition/rendering tools live under ``tools/media-player-stress``
because fixture bytes are test inputs, not product content.  This module is
the application-facing seam: it loads the one approved registry, rechecks the
cached bytes and ffprobe metadata, and then requires typed provider/grant
verifiers before returning a local source descriptor.  It never accepts a
caller-supplied URL or media metadata and never creates provider state or a
playback grant.
"""

