def _spellings(table: dict[int, tuple[str, ...]]) -> dict[str, int]:
    found: dict[str, int] = {}
    for value, spellings in table.items():
        for spelling in spellings:
            if found.setdefault(spelling, value) != value:
                raise ValueError(f"number word {spelling!r} has two values")
    return found


